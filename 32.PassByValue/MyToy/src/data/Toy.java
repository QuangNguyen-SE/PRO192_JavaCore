package data;

import java.util.Date;

/**
 *
 * @author LENOVO
 */
public class Toy {
   
    public String name;
    public double price;
    Date date=new Date();

    public Toy() {
        //Default constructor, null constructor
    }

    public Toy(String name, double price) {
        this.name = name;
        this.price = price;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public double getPrice() {
        return price;
    }

    public void setPrice(double price) {
        this.price = price;
    }

    public Date getDate() {
        return date;
    }

    public void setDate(Date date) {
        this.date = date;
    }

    @Override
    public String toString() {
        return String.format("%15s|%4.1f", name, price);
    }
    
    
    
}
